const MADE = new Set();                        // keys generated by ensureMobaLooks (this page)
const hx = (n) => '#' + ((n >>> 0) & 0xffffff).toString(16).padStart(6, '0');
function shade(color, amt) {
  const f = (c) => Math.max(0, Math.min(255, Math.round(amt < 0 ? c * (1 + amt) : c + (255 - c) * amt)));
  return (f((color >> 16) & 255) << 16) | (f((color >> 8) & 255) << 8) | f(color & 255);
}
const sh = (color, amt) => hx(shade(color, amt));

// ───────────────────────── canvas helpers ─────────────────────────
function rr(ctx, x, y, w, h, r) {
  r = Math.max(0, Math.min(r, w / 2, h / 2));
  ctx.beginPath();
  ctx.moveTo(x + r, y);
  ctx.arcTo(x + w, y, x + w, y + h, r);
  ctx.arcTo(x + w, y + h, x, y + h, r);
  ctx.arcTo(x, y + h, x, y, r);
  ctx.arcTo(x, y, x + w, y, r);
  ctx.closePath();
}
function ell(ctx, cx, cy, rx, ry, rot = 0) { ctx.beginPath(); ctx.ellipse(cx, cy, rx, ry, rot, 0, Math.PI * 2); }
function poly(ctx, pts) {
  ctx.beginPath();
  ctx.moveTo(pts[0], pts[1]);
  for (let i = 2; i < pts.length; i += 2) ctx.lineTo(pts[i], pts[i + 1]);
  ctx.closePath();
}
function paint(ctx, fill, stroke = INK, lw = 1.3) {
  if (fill) { ctx.fillStyle = fill; ctx.fill(); }
  if (stroke) { ctx.strokeStyle = stroke; ctx.lineWidth = lw; ctx.stroke(); }
}
function line(ctx, x0, y0, x1, y1, color = INK, lw = 1.3) {
  ctx.beginPath(); ctx.moveTo(x0, y0); ctx.lineTo(x1, y1);
  ctx.strokeStyle = color; ctx.lineWidth = lw; ctx.stroke();
}
function dot(ctx, x, y, r, fill, stroke = null, lw = 1) { ell(ctx, x, y, r, r); paint(ctx, fill, stroke, lw); }

/** Register a texture spec (display w×h, origin ox/oy, resolution) — drawn in ensureMobaLooks. */
const SPECS = [];
function spec(key, w, h, ox, oy, draw, extra = {}) {
  META[key] = { w, h, ox, oy, res: extra.res || 2, ...extra };
  SPECS.push({ key, draw });
}

function makeCanvasTex(scene, key) {
  const m = META[key];
  const s = SPECS.find((p) => p.key === key);
  if (!m || !s) return false;
  if (scene.textures.exists(key)) { MADE.add(key); return true; }
  const tex = scene.textures.createCanvas(key, Math.ceil(m.w * m.res), Math.ceil(m.h * m.res));
  if (!tex) return false;
  const ctx = tex.getContext();
  ctx.save();
  ctx.scale(m.res, m.res);
  ctx.lineJoin = 'round'; ctx.lineCap = 'round';
  try { s.draw(ctx, m.w, m.h); } catch (e) { console.warn('[looks] draw failed', key, e); }
  ctx.restore();
  tex.refresh();
  MADE.add(key);
  return true;
}

export function lookMeta(key) { return META[key] || null; }
/** Origin + display size for an Image showing a looks.js texture (no-op for other keys). */
export function applyLook(img, key) {
  const m = META[key || img?.texture?.key];
  if (!img || !m) return img;
  img.setOrigin(m.ox, m.oy);
  img.setDisplaySize(m.w * (m.scale || 1), m.h * (m.scale || 1));
  return img;
}

